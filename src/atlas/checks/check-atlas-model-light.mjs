import { createRequire } from "node:module";
import assert from "node:assert/strict";
import { usePublishedFixture } from "./published-fixture.mjs";
const { chromium } = createRequire(import.meta.url)("playwright");
const browser = await chromium.launch({ headless: true, channel: "chrome" });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  await usePublishedFixture(page);
  const upstream = [];
  page.on("request", (request) => { if (/sig\.atmo-auvergnerhonealpes|cartagene\.cerema/.test(request.url())) upstream.push(request.url()); });
  // Let time advance: a frozen Date keeps Leaflet's tile fade at opacity zero.
  await page.clock.install({ time: new Date("2026-09-25T10:00:00Z") });
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(process.env.ATLAS_URL || "http://localhost:3000/atlas");
  await page.locator(".leaflet-container").waitFor();
  assert.equal(await page.getByRole("checkbox", { checked: true }).count(), 1, "Only inventory is enabled initially");
  assert.equal(await page.getByRole("checkbox", { name: /Lichens|Bio-accumulation|Chauffage résidentiel|Cultures potagères|Institut écocitoyen/ }).count(), 0, "Illustrative Institut layers are hidden");
  const labels = await page.getByRole("checkbox").evaluateAll((inputs) => inputs.map((input) => input.closest("label").textContent));
  assert.ok(labels.findIndex((label) => label.includes("Stations de mesure")) < labels.findIndex((label) => label.includes("PM₂.₅ · modèle")), "Stations appear before model layers");
  const models = [["pm25", "PM₂.₅"], ["pm10", "PM₁₀"], ["no2", "NO₂"], ["o3", "O₃"]];
  assert.equal(await page.getByLabel("Polluant du fond Atmo").count(), 0, "Old selector is removed");
  for (const [id, label] of models) {
    await page.getByRole("checkbox", { name: new RegExp(`${label} · modèle`) }).check();
    const legend = page.getByRole("figure", { name: `Échelle ${label}`, exact: true });
    await legend.waitFor();
    assert.equal(await legend.locator("img").count(), 0, "Legend is native HTML, not a provider image");
    assert.ok((await legend.boundingBox()).height < 260, "Legend stays compact with full health-protection labels");
    await page.locator(`.atmo-model-tile[data-pollutant="${id}"].leaflet-tile-loaded`).first().waitFor({ timeout: 45000 });
    await page.getByText(`Chargement de la carte ${label}…`, { exact: true }).waitFor({ state: "hidden", timeout: 45000 });
    assert.ok(await page.locator(`.atmo-model-tile[data-pollutant="${id}"]`).evaluateAll((tiles) => tiles.some((tile) => {
      const pixels = tile.getContext("2d").getImageData(0, 0, 256, 256).data;
      for (let i = 3; i < pixels.length; i += 4) if (pixels[i] > 0) return true;
      return false;
    })), `${id} contains visible raster pixels`);
  }
  assert.equal(await page.getByText(/La carte publiée .* est indisponible/).count(), 0);
  assert.equal(await page.getByRole("checkbox", { name: /Stations de mesure · Atmo/ }).isChecked(), false);
  const pm25 = page.getByRole("slider", { name: "Opacité · PM₂.₅ · modèle", exact: true });
  await pm25.focus(); await pm25.press("Home"); await pm25.press("ArrowRight");
  assert.equal(await pm25.inputValue(), "0.2");
  assert.equal(await page.getByRole("slider", { name: "Opacité · NO₂ · modèle", exact: true }).inputValue(), "0.55");
  await page.getByRole("checkbox", { name: /PM₂.₅ · modèle/ }).uncheck();
  assert.equal(await page.locator('.atmo-model-tile[data-pollutant="pm25"]').count(), 0);
  assert.ok(await page.locator('.atmo-model-tile[data-pollutant="no2"]').count() > 0);
  await page.getByRole("checkbox", { name: /Stations de mesure · Atmo/ }).check();
  assert.ok(await page.locator('.atmo-model-tile[data-pollutant="no2"]').count() > 0, "Stations do not replace model overlays");
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.locator(".leaflet-container").scrollIntoViewIfNeeded();
  await page.locator(".leaflet-container").screenshot({ path: "/tmp/atlas-atmo-model.png" });
  for (const [, label] of models) await page.getByRole("checkbox", { name: new RegExp(`${label} · modèle`) }).uncheck();
  assert.equal(await page.locator(".atmo-model-tile").count(), 0);
  await page.getByRole("checkbox", { name: /Pollution lumineuse/ }).check();
  await page.getByLabel("Mois · Pollution lumineuse").waitFor({ timeout: 35000 });
  await page.waitForFunction(() => document.querySelectorAll(".leaflet-cerema-light-pane path").length === 10);
  assert.equal(await page.locator(".leaflet-cerema-light-pane path").count(), 10);
  assert.equal(await page.getByLabel("Mois · Pollution lumineuse").inputValue(), "2025-09");
  await page.getByLabel("Mois · Pollution lumineuse").selectOption("2025-12");
  await page.getByRole("checkbox", { name: /Pollution lumineuse/ }).uncheck();
  await page.getByRole("checkbox", { name: /Pollution lumineuse/ }).check();
  assert.equal(await page.getByLabel("Mois · Pollution lumineuse").inputValue(), "2025-12", "Manual selection survives toggling the layer");
  await page.getByText("Consulter les 10 communes", { exact: true }).click();
  await page.getByRole("button", { name: /^Passy ·/ }).click();
  await page.getByRole("dialog").waitFor();
  assert.match(await page.getByRole("dialog").innerText(), /empreinte lumineuse/);
  await page.getByRole("dialog").screenshot({ path: "/tmp/atlas-cerema-details.png" });
  await page.getByRole("button", { name: "Fermer la fiche" }).click();
  await page.locator(".leaflet-container").screenshot({ path: "/tmp/atlas-cerema-map.png" });
  await page.getByRole("checkbox", { name: /Pollution lumineuse/ }).uncheck();
  assert.equal(await page.locator(".leaflet-cerema-light-pane").count(), 0);
  await page.getByRole("checkbox", { name: /Stations de mesure · Atmo/ }).uncheck();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: /^Couches/ }).click();
  assert.equal(await page.getByRole("checkbox", { name: /Lichens|Bio-accumulation|Chauffage résidentiel|Cultures potagères|Institut écocitoyen/ }).count(), 0, "Demo layers are also hidden in the mobile drawer");
  await page.getByRole("checkbox", { name: /Pollution lumineuse/ }).check();
  await page.getByLabel("Mois · Pollution lumineuse").waitFor();
  await page.getByRole("checkbox", { name: /PM₂.₅ · modèle/ }).check();
  await page.getByRole("checkbox", { name: /Stations de mesure · Atmo/ }).check();
  await page.getByRole("button", { name: "Voir la carte" }).click();
  await page.getByRole("button", { name: "Couches 4", exact: true }).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  assert.deepEqual(errors, []);
  assert.deepEqual(upstream, [], "Atmo and Cerema use published exports, never provider requests");
  console.log("PASS: four independent Atmo models, separate stations, individual opacity, ten Cerema communes, details, defaults and mobile counts");

  // Independent provider failures must not disable the rest of the atlas.
  const outage = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await usePublishedFixture(outage);
  const wmsPattern = "**/data/atmo-model-pm25.json*";
  const lightPattern = "**/data/cerema-light.json*";
  await outage.route(wmsPattern, (route) => route.abort());
  await outage.route(lightPattern, (route) => route.abort());
  await outage.goto(process.env.ATLAS_URL || "http://localhost:3000/atlas");
  await outage.getByRole("checkbox", { name: /PM₂.₅ · modèle/ }).check();
  await outage.getByText(/La carte publiée PM₂.₅ est indisponible/).waitFor();
  await outage.getByRole("checkbox", { name: /Pollution lumineuse/ }).check();
  await outage.getByRole("button", { name: "Réessayer Cerema", exact: true }).waitFor();
  assert.equal(await outage.getByRole("checkbox", { name: /Sources de pollution potentielle/ }).isChecked(), true);
  await outage.unroute(lightPattern);
  await outage.getByRole("button", { name: "Réessayer Cerema", exact: true }).click();
  await outage.getByLabel("Mois · Pollution lumineuse").waitFor({ timeout: 35000 });
  await outage.unroute(wmsPattern);
  await outage.getByRole("button", { name: "Réessayer la carte PM₂.₅", exact: true }).click();
  await outage.locator(".atmo-model-tile.leaflet-tile-loaded").first().waitFor({ timeout: 45000 });
  await outage.getByText("Chargement de la carte PM₂.₅…", { exact: true }).waitFor({ state: "hidden", timeout: 45000 });
  assert.equal(await outage.getByText(/La carte publiée PM₂.₅ est indisponible/).count(), 0);
  console.log("PASS: provider failures remain isolated and retries recover both overlays");
} finally { await browser.close(); }
