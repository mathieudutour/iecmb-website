import { createRequire } from "node:module";
import assert from "node:assert/strict";
import { usePublishedFixture } from "./published-fixture.mjs";
const { chromium } = createRequire(import.meta.url)("playwright");
const browser = await chromium.launch({ headless: true, channel: "chrome" });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await usePublishedFixture(page);
  const upstream = [];
  page.on("request", (request) => { if (/hubeau\.eaufrance/.test(request.url())) upstream.push(request.url()); });
  const errors = [], warnings = [];
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("console", (message) => { if (message.type() === "warning") warnings.push(message.text()); });
  // Force an outdated catalogue, leaving actual datasets untouched.
  if (!process.env.ATLAS_DATA_DIR) await page.route("**/iec-atlas-data/manifest.json*", async (route) => {
    const response = await route.fetch();
    const data = await response.json();
    for (const entry of Object.values(data.datasets)) entry.lastSuccessAt = "2020-01-01T00:00:00Z";
    await route.fulfill({ response, json: data });
  });
  await page.goto(process.env.ATLAS_URL || "http://localhost:3000/atlas");
  await page.locator(".leaflet-container").waitFor();
  assert.equal(await page.getByRole("checkbox", { checked: true }).count(), 1);
  await page.getByRole("checkbox", { name: /Achats de pesticides/ }).check();
  const year = page.getByLabel("Année · Achats de pesticides");
  await year.waitFor({ timeout: 65000 });
  assert.equal(await year.inputValue(), "2024");
  assert.equal(await page.locator(".leaflet-pesticide-purchases-pane path").count(), 5);
  await page.getByText("Consulter les 5 zones postales", { exact: true }).click();
  await page.getByRole("button", { name: /^74190 · Passy/ }).click();
  const dialog = page.getByRole("dialog");
  await dialog.waitFor();
  assert.match(await dialog.innerText(), /12,678 kg/);
  assert.match(await dialog.innerText(), /Historique annuel/);
  assert.match(await dialog.innerText(), /tefluthrine/);
  await page.getByRole("button", { name: "Fermer la fiche" }).click();
  await page.getByRole("button", { name: /^74700/ }).click();
  assert.match(await dialog.innerText(), /476,165 kg · partiel/);
  await page.getByRole("button", { name: "Fermer la fiche" }).click();
  await year.selectOption("2023");
  await page.getByRole("checkbox", { name: /Achats de pesticides/ }).uncheck();
  assert.equal(await page.locator(".leaflet-pesticide-purchases-pane").count(), 0);
  await page.getByRole("checkbox", { name: /Achats de pesticides/ }).check();
  assert.equal(await year.inputValue(), "2023");
  await page.getByText("Chargement des jeux de données publiés…", { exact: true }).waitFor({ state: "hidden", timeout: 60000 });
  assert.equal(await page.getByText(/Certains imports sont indisponibles/).count(), 0);
  assert.ok(warnings.some((warning) => warning.includes("[Atlas] Imports")), "Import diagnostics go to console");
  await page.locator(".leaflet-container").screenshot({ path: "/tmp/atlas-pesticides.png" });
  assert.deepEqual(errors, []);
  assert.deepEqual(upstream, [], "Pesticide data uses only the published export");
  console.log("PASS live pesticide data, five zones, quantities, partial records, years, detail overlay, toggle and console-only import diagnostics");

  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  await usePublishedFixture(mobile);
  await mobile.route("**/data/pesticide-purchases.json*", (route) => route.fulfill({ status: 503, body: "unavailable" }));
  await mobile.goto(process.env.ATLAS_URL || "http://localhost:3000/atlas");
  await mobile.locator(".leaflet-container").waitFor();
  await mobile.getByRole("button", { name: /^Couches/ }).click();
  await mobile.getByRole("checkbox", { name: /Achats de pesticides/ }).check();
  await mobile.getByRole("button", { name: "Réessayer les achats" }).waitFor();
  assert.equal(await mobile.locator(".leaflet-pesticide-purchases-pane path").count(), 0);
  await mobile.unroute("**/data/pesticide-purchases.json*");
  await mobile.getByRole("button", { name: "Réessayer les achats" }).click();
  await mobile.getByLabel("Année · Achats de pesticides").waitFor({ timeout: 65000 });
  await mobile.getByText("Consulter les 5 zones postales", { exact: true }).click();
  await mobile.getByRole("button", { name: /^74190 · Passy/ }).click();
  await mobile.getByRole("dialog", { name: "Zone postale 74190" }).waitFor();
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  console.log("PASS mobile controls, upstream error and retry, responsive details");
} finally { await browser.close(); }
