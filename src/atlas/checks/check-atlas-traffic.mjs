import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const {chromium}=createRequire(import.meta.url)('playwright');
const browser=await chromium.launch({headless:true,channel:'chrome'});
try {
  for (const width of [1440,390]) {
    const page=await browser.newPage({viewport:{width,height:1000}});
    const errors=[];page.on('pageerror',error=>errors.push(error.message));
    await page.goto(process.env.ATLAS_URL || 'http://localhost:3000/atlas');
    const toggle=page.getByRole('checkbox',{name:'Trafic routier annuel DDT de Haute-Savoie',exact:true});
    assert.equal(await page.locator('[data-road]').count(),0);
    await page.getByRole('checkbox',{name:'Sources de pollution potentielle Inventaire écocitoyen',exact:true}).uncheck();
    await toggle.check();
    await page.getByText('27 tronçons · 20 avec un comptage. Cliquez sur une route pour consulter sa fiche.',{exact:true}).waitFor();
    await page.locator('[data-road]').first().waitFor({state:'attached'});
    assert.equal(await page.locator('[data-road]').count(),27);
    for(const road of ['A40','D1205','D909','D1212','D13','D39','D902','D339','N205']) assert.ok(await page.locator(`[data-road="${road}"]`).count()>0);
    assert.equal(await page.locator('[data-road][stroke-dasharray]').count(),7);
    assert.equal(await page.locator('[data-road="D339"]').count(),1);
    assert.equal(await page.locator('[data-road="N205"]').count(),2);
    assert.match(await page.locator('[data-road="D339"]').getAttribute('aria-label'),/10\s*530 véhicules/);
    assert.match(await page.locator('[data-road="N205"]:not([stroke-dasharray])').getAttribute('aria-label'),/18\s*628 véhicules/);
    const a40=page.getByRole('button',{name:/^A40 · Point de comptage 11 ·/});
    assert.equal(await a40.getAttribute('stroke'),'#b91c1c');
    const d13=page.getByRole('button',{name:/^D13 · Point de comptage 11 ·/});
    assert.equal(await d13.getAttribute('stroke'),'#15803d');
    await a40.focus();await page.keyboard.press('Enter');
    const dialog=page.getByRole('dialog');await dialog.waitFor();
    assert.match(await dialog.innerText(),/21\s*913 véhicules \/ jour/);
    assert.match(await dialog.innerText(),/2024/);
    assert.match(await dialog.innerText(),/7,67 %/);
    assert.match(await dialog.innerText(),/CAP11/);
    assert.ok(await dialog.evaluate(el=>el.matches(':modal')));
    assert.equal(await dialog.locator('[data-atlas-detail-body]').evaluate(el=>el.scrollWidth>el.clientWidth),false);
    await page.screenshot({path:`/tmp/atlas-traffic-detail-${width}.png`});
    await page.keyboard.press('Escape');
    assert.ok(await a40.evaluate(el=>document.activeElement===el),'Keyboard focus returns to SVG road');
    const opacity=page.getByRole('slider',{name:'Opacité · Trafic routier annuel',exact:true});
    await opacity.fill('0.5');
    assert.equal(await a40.getAttribute('stroke-opacity'),'0.5');
    await page.screenshot({path:`/tmp/atlas-traffic-map-${width}.png`});
    const missing=page.locator('[data-road][stroke-dasharray]').first();
    await missing.focus();await page.keyboard.press('Enter');
    await page.getByRole('dialog').getByText('Comptage non disponible',{exact:true}).waitFor();
    assert.match(await page.getByRole('dialog').innerText(),/aucun comptage exploitable/);
    await page.keyboard.press('Escape');await toggle.uncheck();
    assert.equal(await page.locator('[data-road]').count(),0);
    assert.deepEqual(errors,[]);
    console.log(`PASS traffic ${width}px: 9 roads, 27 CCPMB sections, 20 published counts, 7 unknowns, palette, units, opacity, keyboard and overlay`);
    await page.close();
  }
} finally {await browser.close();}
