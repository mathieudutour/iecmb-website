import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
const { chromium } = createRequire(import.meta.url)('playwright');
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(process.env.ATLAS_URL || 'http://localhost:3000/atlas', { timeout: 90000 });
  const trigger = page.getByRole('button', { name: /^Couches/ });
  const drawer = page.getByRole('dialog', { name: 'Couches de l’atlas' });
  await trigger.waitFor();
  assert.equal(await page.getByRole('checkbox').count(), 0, 'Mobile layer list is initially hidden');
  assert.equal(await page.getByRole('complementary', { name: 'Couches de l’atlas' }).count(), 0);
  await trigger.click();
  await drawer.waitFor();
  assert.equal(await trigger.getAttribute('aria-expanded'), 'true');
  assert.equal(await page.evaluate(() => document.body.style.overflow), 'hidden');
  const close = drawer.getByRole('button', { name: 'Fermer les couches' });
  await close.focus(); await page.keyboard.press('Shift+Tab');
  assert.ok(await drawer.getByRole('button', { name: 'Voir la carte' }).evaluate(el => el === document.activeElement));
  await page.keyboard.press('Tab');
  assert.ok(await close.evaluate(el => el === document.activeElement));
  const water = drawer.getByRole('checkbox', { name: 'Cours d’eau Institut écocitoyen · données fictives', exact: true });
  assert.equal(await water.isChecked(), false);
  await water.check();
  assert.equal(await page.locator('.rivers-station-pin[title^="Institut ·"]').count(), 5);
  await water.uncheck();
  assert.equal(await page.locator('.rivers-station-pin[title^="Institut ·"]').count(), 0);
  await drawer.getByRole('checkbox', { name: 'Eaux de baignade Institut écocitoyen · données fictives', exact: true }).check();
  const opacity = drawer.getByRole('slider', { name: 'Opacité · Eaux de baignade', exact: true });
  await opacity.focus(); await opacity.press('Home');
  for (let i = 0; i < 7; i++) await opacity.press('ArrowRight');
  const geometry = await drawer.boundingBox();
  assert.ok(geometry.x === 0 && geometry.y === 0 && geometry.width < 390 && geometry.height <= 844);
  assert.equal(await drawer.evaluate(el => el.scrollWidth > el.clientWidth), false);
  await page.screenshot({ path: '/tmp/atlas-sidebar-mobile.png' });
  await page.keyboard.press('Escape');
  assert.equal(await drawer.count(), 0);
  assert.ok(await trigger.evaluate(el => el === document.activeElement));
  assert.notEqual(await page.evaluate(() => document.body.style.overflow), 'hidden');
  await page.screenshot({ path: '/tmp/atlas-sidebar-mobile-closed.png' });
  await trigger.click();
  assert.equal(await water.isChecked(), false, 'Layer choices survive closing');
  assert.equal(await drawer.getByRole('slider', { name: 'Opacité · Eaux de baignade', exact: true }).inputValue(), '0.5');
  await page.mouse.click(385, 400);
  assert.equal(await drawer.count(), 0, 'Backdrop closes drawer');
  await trigger.click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  const sidebar = page.getByRole('complementary', { name: 'Couches de l’atlas' });
  await sidebar.waitFor();
  assert.equal(await drawer.count(), 0);
  assert.notEqual(await page.evaluate(() => document.body.style.overflow), 'hidden');
  assert.equal(await sidebar.getByRole('checkbox', { name: 'Cours d’eau Institut écocitoyen · données fictives', exact: true }).isChecked(), false);
  assert.equal(await trigger.count(), 0);
  await page.screenshot({ path: '/tmp/atlas-sidebar-desktop.png' });
  await page.setViewportSize({ width: 768, height: 900 });
  await trigger.waitFor();
  assert.equal(await drawer.count(), 0);
  await trigger.click(); await drawer.getByRole('button', { name: 'Voir la carte' }).click();
  assert.equal(await drawer.count(), 0);
  assert.deepEqual(errors, []);
  console.log('PASS mobile/tablet drawer, default collapsed, layer/opacity persistence, focus trap/restore, Escape/backdrop/buttons, desktop resize');
} finally { await browser.close(); }
